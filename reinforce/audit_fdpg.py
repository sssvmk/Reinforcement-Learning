"""Stage 0b: inventory of the FDPG folder (read-only), SHA-256 hashes, compatibility checks. Writes ./outputs/audit/ and FDPG_INVENTORY.md."""
import json
import os
import re
import sys
import pandas as pd
import yaml
from common import load_config, resolve_fdpg_dir, outdir, md
import compare_with_fdpg as cw


def main():
    cfg = load_config()
    d = resolve_fdpg_dir(cfg)
    if not d or not os.path.isdir(d):
        print("FDPG folder not found -> all FDPG comparisons PENDING")
        return 0
    h = cw.hash_tree(d)
    json.dump(h, open(os.path.join(outdir("audit"), "fdpg_hashes_before.json"), "w"), indent=0)
    ext = {}
    for k in h:
        ext.setdefault(os.path.splitext(k)[1] or "(none)", []).append(k)
    fc = yaml.safe_load(open(os.path.join(d, "config.yaml"), encoding="utf8"))
    pk = [k for k in h if k.endswith((".pkl", ".pickle"))]
    L = ["# FDPG_INVENTORY (generated by audit_fdpg.py; FDPG folder is read-only, %d files hashed)\n" % len(h), "FDPG folder: `%s`\n" % d, "## Files by type\n"]
    L.append(md(pd.DataFrame([[e, len(v)] for e, v in sorted(ext.items())], columns=["extension", "count"])))
    L += ["\n## Pickles (NEVER loaded; any comparison needing only a pickle is PENDING)\n", "%d pickle files, e.g. `%s`\n" % (len(pk), pk[0] if pk else "-")]
    L += ["\n## FDPG settings (from its config.yaml)\n", "```yaml\n" + yaml.safe_dump({k: fc[k] for k in fc if k in ("inventory", "trading", "splits", "seed")}, sort_keys=False) + "```\n"]
    rows = [
        ["Series / TECHM data", "same (3 M5 series, TECHM adjusted close)", "compatible"],
        ["Splits 60/20/20", "same", "compatible"],
        ["Horizon H (90 inv, 250 trading), lead time 2, trading cost 5 bps", "same", "compatible"],
        ["Cost structure (unit 0.6*price, holding 0.005*unit, stockout 0.2*price, fixed 0.5*unit)", "re-implemented identically", "compatible"],
        ["Q_max", "FDPG: none; here: 7*mu for REINFORCE and for evidence (B)", "NOT like-for-like in (A); (B) reproduction check uses Q_max=None"],
        ["Discount", "FDPG: undiscounted sum of rewards; here gamma=0.99/0.995 in the gradient only, J reported undiscounted", "reported J compatible"],
        ["Reward normalisation", "FDPG: its own norm; here: std of cover-policy (inv) / buy-and-hold (trading) train-window returns", "normalised J in (A) only approximately comparable; (B) is exact"],
        ["Budget", "FDPG full: 40,000 training rollouts, 10 seeds; here: 40,000 episodes, 10 seeds", "compatible"],
        ["Validation rollouts", "not counted in either budget", "compatible"],
        ["Tuning effort", "FDPG: 9 configs x 2 seeds x 20,000 rollouts; here: 18 configs x 2 seeds x 20,000 episodes", "different (stated in README)"],
        ["Seeds / code", "different code base and seed streams", "seeds not paired -> Mann-Whitney"],
        ["Walk-forward FDPG policies", "fold-specific thetas not saved, but FDPG's walk-forward result CSVs (3 expanding folds, 5 seeds) are", "compared on identical folds by walkforward_compare.py (our methods retrained on FDPG's folds; FDPG rows read from its CSVs)"],
    ]
    L += ["\n## Compatibility\n", md(pd.DataFrame(rows, columns=["item", "FDPG vs this project", "status"]))]
    open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "FDPG_INVENTORY.md"), "w", encoding="utf8").write("\n".join(L) + "\n")
    print("wrote FDPG_INVENTORY.md;", len(h), "files hashed")


if __name__ == "__main__":
    sys.exit(main())

