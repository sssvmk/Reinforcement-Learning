"""Trading business-metric evaluation of the agent pool on the TEST period (primary fold) -> outputs/business_metrics_trading.md"""
import numpy as np, pandas as pd
from scipy.stats import spearmanr
from common import load_config, make_folds
from data_trading import load_all
from domains import TradingDomain, replay_table
from metrics import trading_performance

cfg = load_config()
data, _ = load_all(cfg)
d = data[0]
f = make_folds(d.N, cfg)["primary"]
dom = TradingDomain(d, f, cfg)
pool = dom.build_pool(1)
H = cfg["mdp"]["H"]
lo_o, hi_o = dom.rng_of("ope")
lo_t, hi_t = dom.rng_of("test")

rows = []
for a in pool:
    p = trading_performance(dom.daily_returns(a, "test"))
    g = trading_performance(replay_table(dom.G(a), dom.data.fwd_ret, lo_t, hi_t, 0.0))
    p.update(turnover=dom.turnover_and_gross(a, "test"), gross_cum_return=g["cum_return"], agent=a.name,
             J_true_ope=float(dom.V(a, 0.1, "ope")[lo_o:hi_o - H, 0].mean()))
    rows.append(p)
df = pd.DataFrame(rows).set_index("agent")
cols = ["cum_return", "profit_per_100k", "log_return", "cont_rate_pa", "gross_cum_return", "ann_return", "vol", "sharpe",
        "sortino", "max_drawdown", "calmar", "win_rate", "profit_factor", "turnover", "J_true_ope"]
df = df[cols]
df.to_csv("outputs/business_metrics_trading.csv")

learned = df.index.str.startswith(("dqn", "cql"))
rule = ~learned & ~df.index.isin(["buy_hold", "always_flat"]) & ~df.index.str.startswith("random")
bench = pd.DataFrame({
    "oracle_best_by_test_cum": df.loc[df.cum_return.idxmax()],
    "best_by_validation_truth": df.loc[df.J_true_ope.idxmax()],
    "buy_hold": df.loc["buy_hold"],
    "always_flat": df.loc["always_flat"],
    "random_agents_mean": df[df.index.str.startswith("random")].mean(),
    "pool_median": df.median(),
    "rule_agents_median": df[rule].median(),
    "learned_agents_median": df[learned].median()}).T
bench.insert(0, "agent", [df.cum_return.idxmax(), df.J_true_ope.idxmax(), "buy_hold", "always_flat", "-", "-", "-", "-"])

ok = df.index != "always_flat"
cor = {m: float(spearmanr(df.loc[ok, "J_true_ope"], df.loc[ok, m])[0]) for m in ("cum_return", "sharpe", "calmar")}
beat = int((df.drop(["buy_hold"]).cum_return > df.loc["buy_hold", "cum_return"]).sum())
beat_s = int((df.drop(["buy_hold"]).sharpe > df.loc["buy_hold", "sharpe"]).sum())

pk = pd.read_csv("outputs/results/full_rep_metrics.csv")
pk = pk[(pk.cond == "base") & (pk.fold == "primary")]
picks = pk.groupby("method")[["pick_J_true", "pick_test_cum", "pick_test_sharpe"]].median().round(3)
pick_names = pk.groupby("method").pick.agg(lambda s: s.value_counts().index[0])
picks["most_frequent_pick"] = pick_names

out = ["# Trading business-metric evaluation (auto-generated by business_metrics.py)\n",
       f"Primary fold, TEST period {lo_t}-{hi_t} ({hi_t - lo_t} days), TECHM only, 5 bps one-way cost on position changes, "
       "annualised with 252 days. Agents are greedy deterministic policies replayed over the whole period from flat. "
       "J_true_ope = exact-DP value (eps_t=0.1) averaged over start days in the OPE period, i.e. the quantity the estimators target.\n",
       "## Per-agent test performance\n", df.round(3).to_markdown(), "\n",
       "## Benchmarks\n", bench.round(3).to_markdown(), "\n",
       f"Agents beating buy-and-hold on test cumulative return: {beat} of {len(df) - 1}; on Sharpe: {beat_s} of {len(df) - 1}.\n",
       "## Does the OPE-period truth predict test performance? (Spearman across the pool, always_flat excluded)\n",
       "\n".join(f"- J_true_ope vs test {k}: {v:.2f}" for k, v in cor.items()), "\n",
       "## What each estimator's top pick earned on the test period (median over 10 reps)\n", picks.to_markdown(), "\n"]
open("outputs/business_metrics_trading.md", "w", encoding="utf8").write("\n".join(out))
print("\n".join(out[3:12]))
print(cor, beat, beat_s)
print(picks.to_string())
